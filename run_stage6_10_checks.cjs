const fs = require('fs');
const assert = require('assert');
const audio = fs.readFileSync('js/audio.js', 'utf8');
const ui = fs.readFileSync('js/ui.js', 'utf8');
const game = fs.readFileSync('js/game.js', 'utf8');
const css = fs.readFileSync('styles.css', 'utf8');
const html = fs.readFileSync('index.html', 'utf8');
assert(audio.includes('preloadMusic()'), 'preload function exists');
assert(audio.includes('bgm.preload = "auto"') && audio.includes('bgm.load()'), 'media preload/load starts eagerly');
assert(audio.includes('global.fetch(bgmUrl, { cache: "force-cache", credentials: "same-origin" })'), 'same-origin BGM fetch preloads into cache');
assert(audio.includes('state.scene !== "menu" && state.scene !== "boss"'), 'BGM start is scene-gated');
assert(audio.includes('function setScene(scene)'), 'scene controller exists');
assert(audio.includes('scene === "menu" || scene === "boss"'), 'only menu and boss scenes play BGM');
assert(ui.includes('app.Audio.setScene("menu")'), 'menu scene selected on UI init');
assert(ui.includes('app.Audio.setScene("combat")'), 'combat scene silences BGM');
assert(ui.includes('audio.setScene(data.bossActive ? "boss"'), 'boss HUD state drives BGM scene');
assert(game.includes('audio.setScene("silent")'), 'game over silences BGM');
assert(audio.includes('playerAttack: [[420, 0.10, 0, "sawtooth"'), 'spell-cast attack timbre exists');
assert(audio.includes('summonAttack: [[1180, 0.10, 0, "sine"'), 'prism summon timbre exists');
assert(audio.includes('vortexSpawn: [[680, 0.24, 0, "sine"'), 'wind vortex timbre exists');
assert(audio.includes('fortuneActivate: [[72, 0.34, 0, "sawtooth"'), 'earthquake fortune timbre exists');
assert(ui.includes('classList.add("ui-enter")') && ui.includes('classList.add("ui-exit")'), 'modal enter/exit animations are wired');
assert(ui.includes('classList.add("screen-enter")'), 'screen transitions are animated');
assert(css.includes('@keyframes panel-arrive') && css.includes('@keyframes panel-leave'), 'modal animation keyframes exist');
assert(css.includes('prefers-reduced-motion: reduce'), 'reduced motion preference is respected');
assert(html.includes('id="upgradeModal"'), 'upgrade selection UI remains present');
console.log('STAGE6.10 CHECKS PASSED: scene-gated BGM (menu/Boss only), eager MP3 preload/cache, spell/prism/wind/earthquake sound designs, and screen/modal/card transition animations.');
